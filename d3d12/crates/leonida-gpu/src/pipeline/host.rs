        assert_eq!(LinearScope::parse(""), LinearScope::None);
        assert_eq!(LinearScope::parse(" 0 "), LinearScope::None);
        assert_eq!(LinearScope::parse("1"), LinearScope::All);
        let named = LinearScope::parse(" PS_Composite , ,6318F669E4F17D65");
